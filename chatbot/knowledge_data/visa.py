def _build_country_entry(code, data):
    name, exempt_days, office, note = data

    if exempt_days:
        exempt_text = (
            f'【{name}護照的免簽狀態】\n'
            f'{name}國民可以免簽證入境臺灣，停留 {exempt_days} 天。\n'
            f'但請特別注意：免簽證是給觀光、探親、商務短期停留用的，不是給留學用的。\n'
            f'\n'
            f'⚠️ 最重要的一件事：以免簽證或 eVisa 入境臺灣的人，'
            f'依規定「不得在臺灣境內改辦居留簽證」。\n'
            f'也就是說，如果你貪方便免簽飛來臺灣，到了以後是沒有辦法直接換成居留簽證的，'
            f'必須出境回到 {name} 重新申請，機票與時間都會白白損失。\n'
            f'請務必在出發前就在 {name} 辦好居留簽證再入境。\n'
        )
    else:
        exempt_text = (
            f'【{name}護照的免簽狀態】\n'
            f'{name}國民來臺一律須事先申請簽證，沒有免簽證待遇。\n'
            f'所以你本來就必須在出發前完成簽證申請，這一點反而不容易搞錯。\n'
        )

    note_text = f'\n【{name}的特別提醒】\n{note}\n' if note else ''

    content = f"""
【你需要哪一種簽證】
- 就讀學位學程（學士、碩士、博士）：申請「居留簽證」，入境後 30 天內再辦居留證（ARC）。
- 交換學生且在臺 6 個月以內：申請「停留簽證」。
- 只讀華語文中心：申請華語研習用的簽證，達一定條件後才能轉居留簽證。

{exempt_text}
【要去哪裡辦】
{name}的學生請向「{office}」提出申請。
各館處的地址、電話、辦公時間與是否需要預約都不同，
送件前請先查詢：{BOCA_OFFICE_URL}
{note_text}
【需要準備的文件】
1. 線上填寫並列印的簽證申請表（含條碼），本人親簽
2. 6 個月內拍攝的 2 吋白底彩色照片 2 張
3. 護照正本與影本，效期須 6 個月以上且有空白頁
4. 3 個月內開立的健康檢查合格證明正本與影本
5. 學校核發的入學許可通知書正本與影本
6. 最高學歷畢業證書與歷年成績單正本與影本
7. 財力證明正本與影本（須顯示 6 個月經常性財力）

在 {name} 作成的文件，須經上述駐外館處驗證；
中文、英文以外的文件要另附經驗證的中文或英文譯本。

【時間規劃】
居留簽證審核作業約需 8 個工作天，但這不含文件驗證與預約排隊的時間。
建議拿到入學許可後就立刻開始準備，不要等到開學前一個月才辦。
""".strip()

    return {
        'category': 'visa',
        'country': code,
        'title': f'{name}學生來臺就學的簽證怎麼辦？',
        'keywords': (
            f'簽證, 居留簽證, 停留簽證, visa, resident visa, {name}, {code}, '
            f'免簽, visa exempt, 駐外館處, 代表處'
        ),
        'content': content,
        'source_url': BOCA_VISA_URL,
    }


