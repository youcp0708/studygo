    po = polib.pofile(path)
    entry_map = {e.msgid: e for e in po}
    updated = 0
    added = 0
    for msgid, trans in translations.items():
        if msgid in entry_map:
            if not entry_map[msgid].msgstr:
                entry_map[msgid].msgstr = trans[lang]
                updated += 1
        else:
            e = polib.POEntry(msgid=msgid, msgstr=trans[lang])
            po.append(e)
            added += 1
    po.save(path)
    po.save_as_mofile(path.replace('.po', '.mo'))
    sys.stdout.buffer.write((f'{lang}: updated {updated}, added {added}\n').encode('utf-8'))

