for lang in LANGS:
    po_path = os.path.join(LOCALE_DIR, lang, 'LC_MESSAGES', 'django.po')
    mo_path = po_path.replace('.po', '.mo')
    po = polib.pofile(po_path)
    added = 0
    for msgid, trans in TRANSLATIONS.items():
        if po.find(msgid) is None:
            entry = polib.POEntry(msgid=msgid, msgstr=trans.get(lang, ''))
            po.append(entry)
            added += 1
    po.save()
    po.save_as_mofile(mo_path)
    print(f"{lang}: added {added}, total {len(po)}")
